-- =========================================
-- 5. ACARA
-- =========================================

CREATE TABLE acara (
    id_acara INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tipe_acara VARCHAR(50),
    nama_acara VARCHAR(255) NOT NULL,
    nama_klien VARCHAR(255),
    lokasi VARCHAR(255),
    tanggal_mulai DATE,
    tanggal_selesai DATE,
    is_spesifik BOOLEAN NOT NULL DEFAULT FALSE,
    is_aktif BOOLEAN NOT NULL DEFAULT TRUE,

    CONSTRAINT chk_acara_tanggal
        CHECK (
            tanggal_mulai IS NULL
            OR tanggal_selesai IS NULL
            OR tanggal_mulai <= tanggal_selesai
        )
);
