-- Tabel kecocokan
CREATE TABLE kecocokan (
    id_kecocokan   INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nama_kecocokan VARCHAR(10) NOT NULL UNIQUE
);

-- Tabel provinsi
CREATE TABLE provinsi (
    id_provinsi   INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nama_provinsi VARCHAR(50) NOT NULL UNIQUE,
    pulau         VARCHAR(30) NOT NULL,

    CONSTRAINT chk_provinsi_pulau CHECK (pulau IN ('Sumatera', 'Jawa', 'Bali & Nusa Tenggara',
                                            'Kalimantan', 'Sulawesi', 'Maluku', 'Papua'))
);

-- Tabel alat_musik
CREATE TABLE alat_musik (
    id_alat_musik   INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nama_alat_musik VARCHAR(50) NOT NULL UNIQUE,
    jumlah          INT NOT NULL DEFAULT 1,

    CONSTRAINT chk_alat_musik_jumlah CHECK (jumlah >= 1)
);

-- Tabel jasa
CREATE TABLE jasa (
    id_jasa       INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tipe_jasa     VARCHAR(5) NOT NULL,
    nama          VARCHAR(100) NOT NULL UNIQUE,
    deskripsi     TEXT,
    id_provinsi   INT REFERENCES provinsi(id_provinsi) ON DELETE RESTRICT,
    durasi        INT,
    harga_minimum NUMERIC(14, 2) NOT NULL,
    harga_maximum NUMERIC(14, 2) NOT NULL,
    min_performer INT NOT NULL DEFAULT 1,
    link_media    TEXT, -- link video tari atau musiknya
    link_image    TEXT,
    is_aktif      BOOLEAN NOT NULL DEFAULT TRUE,

    CONSTRAINT chk_jasa_tipe          CHECK (tipe_jasa IN ('tari', 'musik')),
    CONSTRAINT chk_jasa_kultur_tari   CHECK (tipe_jasa <> 'tari' OR id_provinsi IS NOT NULL),
    CONSTRAINT chk_jasa_durasi        CHECK (durasi IS NULL OR durasi > 0),
    CONSTRAINT chk_jasa_harga         CHECK (harga_minimum >= 0 AND harga_maximum >= harga_minimum),
    CONSTRAINT chk_jasa_min_performer CHECK (min_performer >= 1)
);

-- Tabel anggota
CREATE TABLE anggota (
    id_anggota     INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    email          VARCHAR(255) NOT NULL UNIQUE,
    password_hash  VARCHAR(255) NOT NULL,
    nama           VARCHAR(100) NOT NULL,
    npm            VARCHAR(12) UNIQUE,
    angkatan_unpar SMALLINT,
    jabatan        VARCHAR(50),
    peran          VARCHAR(50) NOT NULL,
    is_penari      BOOLEAN NOT NULL DEFAULT FALSE,
    is_pemusik     BOOLEAN NOT NULL DEFAULT FALSE,
    is_aktif       BOOLEAN NOT NULL DEFAULT TRUE,

    CONSTRAINT chk_anggota_npm   CHECK (npm IS NULL OR npm ~ '^[0-9]{6,12}$'),
    CONSTRAINT chk_anggota_peran CHECK (peran IN ('admin', 'listra', 'humas', 'pelatih', 'anggota', 'alumni'))
);

-- Tabel acara
CREATE TABLE acara (
    id_acara   INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tipe_acara VARCHAR(12) NOT NULL,
    nama_acara VARCHAR(150) NOT NULL,
    nama_klien VARCHAR(100),
    lokasi     VARCHAR(200),
    is_privat  BOOLEAN NOT NULL DEFAULT FALSE,

    CONSTRAINT chk_acara_tipe  CHECK (tipe_acara IN ('job_external', 'listra')),
    CONSTRAINT chk_acara_klien CHECK (tipe_acara = 'job_external' OR nama_klien IS NULL)
);

-- Tabel acara_jasa
CREATE TABLE acara_jasa (
    id_acara_jasa     INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_acara          INT NOT NULL REFERENCES acara(id_acara) ON DELETE CASCADE,
    id_jasa           INT REFERENCES jasa(id_jasa) ON DELETE RESTRICT,  -- NULL = hari tanpa jasa
    tanggal           DATE NOT NULL,
    jam_mulai         TIME NOT NULL,
    jam_selesai       TIME NOT NULL,
    is_tidak_spesifik BOOLEAN NOT NULL DEFAULT FALSE,

    CONSTRAINT chk_acara_jasa_jam CHECK (jam_selesai > jam_mulai)
);

-- Tabel acara_performer
CREATE TABLE acara_performer (
    id_acara_performer INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_acara_jasa      INT NOT NULL REFERENCES acara_jasa(id_acara_jasa) ON DELETE CASCADE,
    id_anggota         INT REFERENCES anggota(id_anggota) ON DELETE RESTRICT,
    nama_performer     VARCHAR(255),

    CONSTRAINT chk_performer_satu   CHECK ((id_anggota IS NULL) <> (nama_performer IS NULL)),
    CONSTRAINT uq_performer_anggota UNIQUE (id_acara_jasa, id_anggota)
);

-- Tabel testimoni
CREATE TABLE testimoni (
    id_testimoni    INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nama_klien      VARCHAR(100) NOT NULL,
    instansi        VARCHAR(150),
    nama_acara      VARCHAR(150),
    is_acara_privat BOOLEAN NOT NULL DEFAULT FALSE,
    isi_testimoni   TEXT NOT NULL,
    rating          SMALLINT,
    tanggal_input   TIMESTAMP NOT NULL DEFAULT NOW(),
    status          VARCHAR(9) NOT NULL DEFAULT 'menunggu',
    sumber          VARCHAR(8) NOT NULL DEFAULT 'web',
    is_aktif        BOOLEAN NOT NULL DEFAULT FALSE,

    CONSTRAINT chk_testimoni_rating CHECK (rating IS NULL OR rating BETWEEN 1 AND 5),
    CONSTRAINT chk_testimoni_status CHECK (status IN ('menunggu', 'disetujui', 'ditolak')),
    CONSTRAINT chk_testimoni_sumber CHECK (sumber IN ('web', 'whatsapp'))
);

-- Tabel berita
CREATE TABLE berita (
    id_berita       INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    judul           VARCHAR(255) NOT NULL,
    tanggal         DATE NOT NULL,
    url_gambar      TEXT NOT NULL,
    konten          TEXT,
    sumber          VARCHAR(255),
    url_artikel     TEXT,
    is_publik       BOOLEAN NOT NULL DEFAULT FALSE,
    dibuat_pada     TIMESTAMP NOT NULL DEFAULT NOW(),
    diperbarui_pada TIMESTAMP NOT NULL DEFAULT NOW(),

    CONSTRAINT chk_berita_jenis
        CHECK (
            (url_artikel IS NULL AND sumber IS NULL AND konten IS NOT NULL)
            OR (url_artikel IS NOT NULL AND sumber IS NOT NULL AND konten IS NULL)
        )
);

-- Tabel kontak_whatsapp
CREATE TABLE kontak_whatsapp (
    id_kontak      INT PRIMARY KEY DEFAULT 1,
    nomor_wa       VARCHAR(15) NOT NULL,
    nama_humas     VARCHAR(100) NOT NULL,
    template_pesan TEXT,

    CONSTRAINT chk_kontak_satu_baris CHECK (id_kontak = 1),
    CONSTRAINT chk_kontak_nomor      CHECK (nomor_wa ~ '^[0-9]{8,15}$')
);


-- =============================================
-- INDEXES
-- =============================================

CREATE INDEX idx_jasa_provinsi
ON jasa(id_provinsi);

CREATE INDEX idx_acara_jasa_jasa
ON acara_jasa(id_jasa);

CREATE INDEX idx_acara_performer_anggota
ON acara_performer(id_anggota);

-- Paling banyak satu baris tanpa jasa (id_jasa NULL) per hari
CREATE UNIQUE INDEX uq_acara_jasa_kosong
ON acara_jasa(id_acara, tanggal) WHERE id_jasa IS NULL;

-- Email unik tanpa membedakan huruf besar/kecil (budi@x.id = BUDI@x.id)
CREATE UNIQUE INDEX uq_anggota_email_lower
ON anggota(LOWER(email));
