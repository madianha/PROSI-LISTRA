-- =========================================
-- 1. JASA / LAYANAN, BISA MUSIK ATAU TARI
-- =========================================

CREATE TABLE jasa (
    id_jasa INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tipe_jasa VARCHAR(50) NOT NULL,
    nama VARCHAR(255) NOT NULL,
    deskripsi TEXT,
    kecocokan VARCHAR(50),
    durasi INT,
    harga_minimum NUMERIC(14, 2),
    harga_maximum NUMERIC(14, 2),
    min_performer INT DEFAULT 1,
    link_media TEXT,
    link_image TEXT,
    is_aktif BOOLEAN NOT NULL DEFAULT TRUE,

    CONSTRAINT chk_jasa_tipe
        CHECK (tipe_jasa IN ('musik', 'tari')),

    CONSTRAINT chk_jasa_durasi
        CHECK (durasi IS NULL OR durasi > 0),

    CONSTRAINT chk_jasa_harga
        CHECK (
            (harga_minimum IS NULL OR harga_minimum >= 0)
            AND (harga_maximum IS NULL OR harga_maximum >= 0)
            AND (
                harga_minimum IS NULL
                OR harga_maximum IS NULL
                OR harga_minimum <= harga_maximum
            )
        ),

    CONSTRAINT chk_jasa_min_performer
        CHECK (min_performer IS NULL OR min_performer > 0)
);

-- =========================================
-- 2. ALAT MUSIK
-- =========================================

CREATE TABLE alat_musik (
    id_alat_musik INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nama_alat_musik VARCHAR(255) NOT NULL UNIQUE
);

-- =========================================
-- 3. ANGGOTA
-- =========================================

CREATE TABLE anggota (
    id_anggota INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nama VARCHAR(255) NOT NULL,
    email VARCHAR(255) UNIQUE,
    npm VARCHAR(20) UNIQUE,
    angkatan_unpar INT,
    jabatan VARCHAR(255),
    is_aktif BOOLEAN NOT NULL DEFAULT TRUE,

    CONSTRAINT chk_anggota_angkatan
        CHECK (angkatan_unpar IS NULL OR angkatan_unpar > 0)
);


-- =========================================
-- 4. SPESIALISASI UMUM
-- Contoh: pemusik, penari
-- =========================================

CREATE TABLE spesialisasi (
    id_spesialisasi INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    jenis_spesialisasi VARCHAR(255) NOT NULL UNIQUE
);

-- =========================================
-- 5. ACARA
-- =========================================

CREATE TABLE acara (
    id_acara INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tipe_acara VARCHAR(50),
    nama_acara VARCHAR(255) NOT NULL,
    nama_klien VARCHAR(255),
    lokasi VARCHAR(255),
    tanggal_mulai DATE,
    tanggal_selesai DATE,
    is_spesifik BOOLEAN NOT NULL DEFAULT FALSE,
    is_aktif BOOLEAN NOT NULL DEFAULT TRUE,

    CONSTRAINT chk_acara_tanggal
        CHECK (
            tanggal_mulai IS NULL
            OR tanggal_selesai IS NULL
            OR tanggal_mulai <= tanggal_selesai
        )
);